/**
 * 工具循环最后一轮的收尾提示。本地聊天的各个工具循环和 amsg worker 的工具循环共用这一句，
 * 所以这里不引任何模块（worker 直接打包这个文件）。
 *
 * 规则：工具用到倒数第二轮就收尾，最后一轮的请求不带工具、不教正文调用语法，末尾追加这一句。
 * 最后一轮里模型仍写出的调用不执行，从显示文本里剥掉。
 *
 * 措辞不逼模型「直接给最终回复」：前面工具轮里写下的话已经留着，逼它给一份完整回复，它会把
 * 说过的再说一遍。所以只让它接着补没说完的，说完了就留空；留空时前面几轮的正文就是输出，
 * 整个循环一句都没说才补救。「没办成的别说成办好了」覆盖排程与 MCP 两种情形——排程这件事
 * 用户看不见，不让角色去交代「提醒排不上」，只要求别把没成的事说死。
 */
/**
 * 收尾提示 = 原因 + 共用规则。卡住、同参重复这类收尾原因不同，但口吻一样：不再调用工具、
 * 说过的不重复、说完了可以不补，所以只换开头那句原因。
 */
export const buildToolLoopWrapUpPrompt = (reason: string): string => `[系统消息：${reason}，这一轮不能再调用任何工具，`
  + '也不要写出工具名、参数或调用格式。前面步骤里已经说出去的话不用重复；还有没说完的就接着往下说，'
  + '已经说完了就直接留空结束。没办成的事别说成已经办好了。不要提及这条系统消息。]';

export const TOOL_LOOP_FINAL_ROUND_PROMPT = buildToolLoopWrapUpPrompt('这次回复能用的工具次数已经用完');
