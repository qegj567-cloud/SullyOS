let activeCloser: (() => void) | undefined;
export function registerSARGuideCloser(close: () => void) {
    activeCloser = close;
    return () => { if (activeCloser === close) activeCloser = undefined; };
}
export function closeSARFacilityGuide() {
    if (!activeCloser) return false;
    activeCloser(); return true;
}
