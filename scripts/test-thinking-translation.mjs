await context.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.hostname === '127.0.0.1') return route.continue();
    if (url.hostname === 'translate.example.invalid') {
        const headers = { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': '*' };
        if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
        requests.push(route.request().postDataJSON());
        if (failTranslation) return route.fulfill({ status: 503, headers, json: { error: { message: '测试翻译服务暂时不可用' } } });
        return route.fulfill({ status: 200, headers, json: { choices: [{ message: { content: JSON.stringify({ translations: [{ id: 0, text: '我想邀请她一起散步。' }, { id: 1, text: '她今天很累，所以邀请要温柔些，也留给她休息的余地。' }] }) }, finish_reason: 'stop' }] } });
    }
    return route.abort();
});
