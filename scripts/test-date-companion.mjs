// Uses the real DateApp fixture; all model calls are deterministic local test responses.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const output = join(tmpdir(), 'sully-date-companion');
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const errors = [], requests = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir(output, { recursive: true });
const prose = '书架边的那把椅子还空着，我把刚才翻开的书放回原位，留出一点能自在坐下的地方。'.repeat(10);
await page.route('https://date-companion.example.invalid/**', async route => {
    const body = route.request().postDataJSON(); requests.push(body);
    const opening = JSON.stringify(body.messages).includes('(Start sensing...)');
    const content = `⟦OBSERVE⟧\n时间｜午后\n地点｜书房\n状态｜自在\n细节｜把书合上\n⟦/OBSERVE⟧\n${opening ? '林间把书合上，走到门边。\n“要一起坐会儿吗？”<date-voice lang="en">Would you like to sit?</date-voice>' : `[normal] ${prose}\n[happy] "这里留给你。"\n[normal] 我把自己的书放到膝上。\n[normal] 翻回刚才的那一页。`}`;
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { role: 'assistant', content } }] }) });
});
try {
    await page.addInitScript(() => localStorage.setItem('sully-date-entry-guide-v1', 'seen'));
    await page.goto((process.env.DATE_TEST_BASE_URL || 'http://127.0.0.1:4181') + '/test/fixtures/date-companion.html', { waitUntil: 'domcontentloaded', timeout: 180000 });
    await page.getByText('林间', { exact: true }).waitFor({ timeout: 180000 });
    await page.getByText('林间', { exact: true }).click();
    await page.getByRole('button', { name: '选择陪伴文风', exact: true }).click();
    await page.locator('[data-style-id="playful"]').click();
    await page.getByRole('button', { name: '场景与微调', exact: true }).click();
    await page.getByRole('button', { name: '直球偏爱', exact: true }).click();
    await page.getByLabel('陪伴场景描述').fill('本场在书房坐一会儿。');
    assert.equal(await page.locator('[data-default-style]').textContent(), 'cinematic');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: join(output, 'entry-expanded.png'), fullPage: true });
    await page.keyboard.press('Escape');
    await page.screenshot({ path: join(output, 'entry.png'), fullPage: true });
    await page.getByRole('radio', { name: '让 TA 靠近', exact: true }).click();
    assert.equal(requests.length, 0);
    await page.getByRole('button', { name: '确认进入见面' }).click();
    await page.getByRole('button', { name: '见到 TA', exact: true }).waitFor({ timeout: 90000 });
    assert.equal((await page.locator('body').textContent()).includes('⟦OBSERVE⟧'), false);
    assert.equal((await page.locator('body').textContent()).includes('Would you like'), false);
    assert.match(JSON.stringify(requests[0].messages), /轻快幽默/);
    assert.match(JSON.stringify(requests[0].messages), /本场在书房坐一会儿/);
    await page.screenshot({ path: join(output, 'opening.png'), fullPage: true });
    await page.getByRole('button', { name: '见到 TA', exact: true }).click();
    if (!(await page.getByLabel('见面输入', { exact: true }).count())) await page.getByRole('button', { name: '展示输入框', exact: true }).click();
    await page.getByRole('button', { name: '继续', exact: true }).click();
    await page.getByText('Typing...', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(requests.length, 2);
    assert.match(JSON.stringify(requests[1].messages), /不要求制造新事件或推进关系/);
    assert.match(JSON.stringify(requests[1].messages), /直球偏爱/);
    await page.waitForFunction(() => document.querySelector('[data-sar-gal-text]')?.textContent?.startsWith('书架边的那把椅子'));
    if (await page.locator('[data-sar-gal-text] .animate-pulse').count()) await page.locator('[data-sar-gal-text]').click();
    await page.waitForFunction(length => (document.querySelector('[data-sar-gal-text]')?.textContent?.length || 0) >= length, prose.length);
    await page.waitForTimeout(250); // A skipped animation must not truncate the text on its next timer tick.
    assert.equal(await page.locator('[data-sar-gal-text]').textContent(), prose);
    const bounds = await page.locator('[data-sar-gal-text]').evaluate(el => ({ height: el.clientHeight, scroll: el.scrollHeight, viewport: innerHeight }));
    assert.ok(bounds.height <= bounds.viewport * .36, JSON.stringify(bounds));
    assert.ok(bounds.scroll > bounds.height, `long line can scroll inside the dialogue: ${JSON.stringify(bounds)}`);
    await page.locator('[data-sar-gal-text]').hover();
    await page.mouse.wheel(0, 350);
    await page.waitForFunction(() => document.querySelector('[data-sar-gal-text]')?.scrollTop > 0);
    await page.screenshot({ path: join(output, 'long-line.png'), fullPage: true });
    await page.getByRole('button', { name: '打开见面菜单', exact: true }).click();
    await page.getByRole('button', { name: '阅读模式', exact: true }).click();
    await page.locator('.meeting-reading-page').waitFor();
    await page.screenshot({ path: join(output, 'reading.png'), fullPage: true });
    await page.getByRole('button', { name: '测试挂起', exact: true }).click();
    await page.getByRole('button', { name: '测试恢复', exact: true }).click();
    if (!(await page.getByLabel('见面输入', { exact: true }).count())) await page.getByRole('button', { name: '展示输入框', exact: true }).click();
    await page.getByRole('button', { name: '继续', exact: true }).click();
    await page.getByText('Typing...', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(requests.length, 3);
    assert.match(JSON.stringify(requests[2].messages), /轻快幽默/);
    assert.match(JSON.stringify(requests[2].messages), /本场在书房坐一会儿/);
    assert.equal(await page.locator('[data-default-style]').textContent(), 'cinematic');
    await page.getByRole('button', { name: '打开见面菜单', exact: true }).click();
    await page.getByRole('button', { name: '离开', exact: true }).click();
    await page.getByText('林间', { exact: true }).click();
    assert.equal(await page.getByLabel('选择陪伴文风').getAttribute('data-style-value'), 'cinematic');
    await page.getByRole('button', { name: '选择陪伴文风', exact: true }).click();
    await page.locator('[data-style-id="plain"]').click();
    await page.getByRole('button', { name: '场景与微调', exact: true }).click();
    assert.equal(await page.getByLabel('陪伴场景描述').inputValue(), '');
    await page.getByRole('button', { name: '设为角色默认', exact: true }).click();
    assert.equal(await page.locator('[data-default-style]').textContent(), 'cinematic');
    await page.getByRole('button', { name: '确认覆盖角色默认体验', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-default-style]')?.textContent === 'plain');
    await page.waitForFunction(async () => {
        const { DB } = await import('/utils/db.ts');
        const saved = await DB.getCharacter('fixture-date-companion');
        return saved?.dateStyleConfig?.style === 'plain' && saved.dateStyleConfig.pov === 'first-you';
    });
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, requests: requests.length, viewport: '390x844', longLine: bounds, screenshots: output }));
} catch (error) {
    await page.screenshot({ path: join(output, 'failure.png'), fullPage: true }).catch(() => {});
    console.error(JSON.stringify({ errors, body: (await page.locator('body').textContent().catch(() => '')).slice(-2500) }));
    throw error;
} finally { await browser.close(); }
