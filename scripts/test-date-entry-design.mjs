    assert.equal(await page.getByLabel('立绘左右偏移').inputValue(), '20');
    assert.equal(await page.getByLabel('立绘上下偏移').inputValue(), '15');
    const saved = await page.evaluate(async () => (await import('/utils/db.ts')).DB.getCharacter('fixture-date-companion'));
    assert.deepEqual(saved.spriteConfig, { scale: 1.1, x: 20, y: 15 });
    await page.getByRole('button', { name: '返回', exact: true }).click();
    assert.equal(await page.getByRole('radio', { name: '直接见面', exact: true }).getAttribute('aria-checked'), 'true');
    for (const [width, height] of [[320, 640], [430, 932], [1100, 900]]) {
        await page.setViewportSize({ width, height });
        await page.waitForTimeout(120);
        const dimensions = await page.locator('.date-entry').evaluate(root => ({ viewport: root.clientWidth, content: root.scrollWidth,
            fit: [...root.querySelectorAll('.date-ticket__title,.date-ticket__detail')].every(el => el.scrollWidth <= el.clientWidth + 1) }));
        assert.equal(dimensions.content <= dimensions.viewport, true, JSON.stringify(dimensions));
        assert.equal(dimensions.fit, true, `ticket labels fit at ${width}`);
        await page.getByRole('button', { name: '确认进入见面' }).scrollIntoViewIfNeeded();
        await page.screenshot({ path: join(output, `${width}-entry.png`), fullPage: true });
    }
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.getByRole('radio', { name: '靠近 TA', exact: true }).click();
    assert.equal(await page.locator('.date-ticket.is-selected .date-ticket__icon').evaluate(el => getComputedStyle(el).animationName), 'none');
    assert.equal(calls, 0);
    await page.getByRole('radio', { name: '直接见面', exact: true }).click();
    await page.getByRole('button', { name: '确认进入见面' }).click();
