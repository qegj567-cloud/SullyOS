    await features.getByRole('button', { name: '收起观测协议', exact: true }).click();
    for (const width of [320, 390]) {
        await page.setViewportSize({ width, height: 844 });
        await features.scrollIntoViewIfNeeded();
        await features.screenshot({ path: join(output, `${width}-feature-settings.png`) });
        assert.equal(await features.evaluate(el => el.scrollWidth <= el.clientWidth), true);
    }
    const switches = await page.locator('.date-setting-switch').evaluateAll(elements => elements.filter(el => el.checkVisibility()).map(el => ({width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height})));
    assert.ok(switches.every(size => size.width >= 44 && size.height >= 44));
    assert.equal(await page.getByLabel('陪伴场景描述').isVisible(), true, 'common settings start expanded');
    assert.equal(await page.getByLabel('陪伴互动基调').isVisible(), true);
    assert.equal(await page.getByRole('button', { name: '保存当前布置', exact: true }).count(), 0);
    assert.equal(await page.getByLabel('本次写作风格').count(), 1);
    await page.getByRole('button', { name: '本次写作风格', exact: true }).click();
    assert.equal(await page.getByRole('dialog', { name: '选择写作风格', exact: true }).getByRole('option').count(), 10);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByLabel('叙事人称', { exact: true }).isVisible(), true);
