    await page.goto((process.env.DATE_TEST_BASE_URL || 'http://127.0.0.1:4181') + '/test/fixtures/date-companion.html', { waitUntil: 'domcontentloaded', timeout: 180000 });
    await page.getByText('林间', { exact: true }).click({ timeout: 180000 });
    await page.locator('.date-ticket').first().waitFor();
    await page.getByRole('button', { name: '选择陪伴文风', exact: true }).click();
    assert.equal(await page.getByRole('dialog', { name: '选择写作风格', exact: true }).getByRole('option').count(), 10);
    await page.getByRole('button', { name: '关闭文风选择', exact: true }).click();
    await page.getByRole('button', { name: '选择陪伴文风', exact: true }).click();
    await page.locator('[data-style-id="slice_of_life"]').click();
    await page.waitForTimeout(700);
    await page.screenshot({ path: join(output, '390-entry.png'), fullPage: true });
    await page.locator('.date-entry').screenshot({ path: join(output, 'preview.png') });
    assert.equal(await page.getByRole('radio', { name: '靠近 TA', exact: true }).getAttribute('aria-checked'), 'true');
    await page.getByRole('radio', { name: '让 TA 靠近', exact: true }).click();
    await page.waitForTimeout(600);
    assert.equal(calls, 0, 'selecting a ticket must not generate an opening');
    assert.equal(await page.getByRole('radio', { name: '让 TA 靠近', exact: true }).getAttribute('aria-checked'), 'true');
    await page.screenshot({ path: join(output, '390-invite.png'), fullPage: true });
    await page.getByRole('radio', { name: '让 TA 靠近', exact: true }).press('ArrowRight');
    assert.equal(await page.getByRole('radio', { name: '直接见面', exact: true }).getAttribute('aria-checked'), 'true');
    await page.getByRole('button', { name: '场景与微调', exact: true }).click();
    await page.getByLabel('陪伴场景描述').fill('雨夜里的书房');
    await page.getByRole('button', { name: '本次写作风格', exact: true }).click();
    await page.getByLabel('搜索文风').fill('日式');
    assert.equal(await page.locator('[data-style-id="playful"]').count(), 1);
    assert.equal(await page.locator('[data-style-id="intense"]').count(), 0);
    await page.screenshot({ path: join(output, '390-style-picker.png'), fullPage: true });
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog', { name: '选择写作风格', exact: true }).count(), 0);
    assert.equal(await page.getByLabel('陪伴场景描述').isVisible(), true);

    await page.screenshot({ path: join(output, '390-settings.png'), fullPage: true });
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.getByRole('radio', { name: '直接见面', exact: true }).getAttribute('aria-checked'), 'true');
    await page.getByRole('button', { name: '打开见面设置', exact: true }).click();
    const features = page.getByRole('region', { name: '见面互动设置', exact: true });
    assert.equal(await features.locator(':scope > .date-feature').count(), 3);
    const actionSwitch = features.getByRole('switch', { name: '开启行动选择', exact: true });
    await features.getByRole('button', { name: '展开行动选择', exact: true }).click();
    assert.equal(await actionSwitch.getAttribute('aria-checked'), 'false', 'expanding details does not enable the feature');
    await actionSwitch.press('Space');
    assert.equal(await actionSwitch.getAttribute('aria-checked'), 'true');
    await actionSwitch.click();
    await features.getByRole('button', { name: '收起行动选择', exact: true }).click();
    await features.getByRole('switch', { name: '切换离开提醒', exact: true }).click();
    await features.getByRole('button', { name: '展开离开提醒', exact: true }).click();
    assert.equal(await page.getByLabel('走开多久后提醒').isVisible(), true);
